    Jugadores.id_jugador,
    Jugadores.nombre,
    Jugadores.apellido,
    Jugadores.pais,
    Jugadores.posicion,
    Jugadores.liga_actual,
    Jugadores.dorsal_equipo,
    Jugadores.dorsal_seleccion,
    Jugadores.valor_mercado,

    Datos.edad,
    Datos.altura,
    Datos.peso,
    Datos.pierna_habil,

    Estadisticas.goles,
    Estadisticas.asistencias,
    Estadisticas.titulos_equipo,
    Estadisticas.titulos_seleccion,
    Estadisticas.titulos_individuales,

    Equipos.nombre_equipo,

    Trayectoria.anio_ingreso,
    Trayectoria.anio_traspaso

FROM Jugadores
INNER JOIN Datos
    ON Jugadores.id_jugador = Datos.id_jugador
INNER JOIN Estadisticas
    ON Jugadores.id_jugador = Estadisticas.id_jugador
INNER JOIN Equipos
    ON Jugadores.id_equipo = Equipos.id_equipo
INNER JOIN Trayectoria
    ON Jugadores.id_jugador = Trayectoria.id_jugador
    AND Equipos.id_equipo = Trayectoria.id_equipo;
    
SELECT
    Equipos.id_equipo,
    Equipos.nombre_equipo,
    Equipos.ciudad,
    Equipos.estadio,
    Equipos.dt_actual,
    Equipos.presidente,
    Equipos.apodo,
    Equipos.anio_creacion,
    Equipos.titulos_nacionales,
    Equipos.titulos_internacionales,
    Equipos.cantidad_socios
FROM Equipos;

SELECT
    Equipos.id_equipo,
    Equipos.nombre_equipo,
    Equipos.ciudad,
    Equipos.estadio,
    Equipos.dt_actual,
    Equipos.presidente,
    Equipos.apodo,
    Equipos.anio_creacion,
    Equipos.titulos_nacionales,
    Equipos.titulos_internacionales,
    Equipos.cantidad_socios,
    COUNT(Jugadores.id_jugador) AS cantidad_jugadores
FROM Equipos
LEFT JOIN Jugadores
    ON Equipos.id_equipo = Jugadores.id_equipo
GROUP BY
    Equipos.id_equipo,
    Equipos.nombre_equipo,
    Equipos.ciudad,
    Equipos.estadio,
    Equipos.dt_actual,
    Equipos.presidente,
    Equipos.apodo,
    Equipos.anio_creacion,
    Equipos.titulos_nacionales,
    Equipos.titulos_internacionales,
    Equipos.cantidad_socios;
    
    SELECT
    Jugadores.id_jugador,
    Jugadores.nombre,
    Jugadores.apellido,
    GROUP_CONCAT(Equipos.nombre_equipo ORDER BY Trayectoria.anio_ingreso SEPARATOR ' - ') AS equipos,
    GROUP_CONCAT(Trayectoria.anio_ingreso ORDER BY Trayectoria.anio_ingreso SEPARATOR ' - ') AS años_ingreso,
    GROUP_CONCAT(Trayectoria.anio_traspaso ORDER BY Trayectoria.anio_ingreso SEPARATOR ' - ') AS años_traspaso
FROM Trayectoria
INNER JOIN Jugadores
    ON Trayectoria.id_jugador = Jugadores.id_jugador
INNER JOIN Equipos
    ON Trayectoria.id_equipo = Equipos.id_equipo
GROUP BY
    Jugadores.id_jugador,
    Jugadores.nombre,
    Jugadores.apellido;

